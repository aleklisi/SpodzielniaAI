"""Registry of audit event types. ``AuditService.record`` accepts only these."""

from __future__ import annotations

from enum import StrEnum


class EventType(StrEnum):
    # Identity & sessions (1.5, 1.6)
    USER_PROVISIONED = "USER_PROVISIONED"
    USER_LOGIN = "USER_LOGIN"
    USER_LOGOUT = "USER_LOGOUT"
    REFRESH_TOKEN_REUSE = "REFRESH_TOKEN_REUSE"  # noqa: S105 - event name, not a secret
    # Private notebook & uploads (Stage 2)
    UPLOAD_REJECTED = "UPLOAD_REJECTED"
    ATTACHMENT_LOCATION_RETAINED = "ATTACHMENT_LOCATION_RETAINED"
    PROCESSING_FAILED = "PROCESSING_FAILED"
    # Promotion & prompt injection (Stage 3)
    PROMPT_INJECTION_DETECTED = "PROMPT_INJECTION_DETECTED"
    QUARANTINE_CONFIRMED = "QUARANTINE_CONFIRMED"
    NOTE_PROMOTED = "NOTE_PROMOTED"
    PROMOTION_FAILED = "PROMOTION_FAILED"
    # Governance & consent (Stage 4)
    ARTICLE_STATUS_CHANGED = "ARTICLE_STATUS_CHANGED"
    CONSENT_SUSPENDED = "CONSENT_SUSPENDED"
    CONSENT_RESUMED = "CONSENT_RESUMED"
    CONSENT_REVOKED = "CONSENT_REVOKED"
    ARTICLE_DEGRADED = "ARTICLE_DEGRADED"
    VECTOR_DRIFT_DETECTED = "VECTOR_DRIFT_DETECTED"
    # Anti-distillation shield (Stage 5)
    COVERAGE_LOCK = "COVERAGE_LOCK"
    HONEYPOT_TRIGGERED = "HONEYPOT_TRIGGERED"
    HONEYPOT_INJECTED = "HONEYPOT_INJECTED"
    VERBATIM_BLOCKED = "VERBATIM_BLOCKED"
    SHIELD_DECISION = "SHIELD_DECISION"
    # Administration (Stage 6)
    ACCOUNT_UNLOCKED = "ACCOUNT_UNLOCKED"
    SECURITY_DASHBOARD_ACCESSED = "SECURITY_DASHBOARD_ACCESSED"
    # LLM configuration (Stage 7)
    LLM_PROVIDER_CHANGED = "LLM_PROVIDER_CHANGED"
    LLM_MODEL_CHANGED = "LLM_MODEL_CHANGED"
    LLM_MODEL_PROBED = "LLM_MODEL_PROBED"
    LLM_CONFIG_DRAFT_CHANGED = "LLM_CONFIG_DRAFT_CHANGED"
    LLM_CONFIG_ACTIVATED = "LLM_CONFIG_ACTIVATED"
    LLM_CONFIG_ROLLED_BACK = "LLM_CONFIG_ROLLED_BACK"
    LLM_PLAYGROUND_USED = "LLM_PLAYGROUND_USED"
    # User management (Stage 8). Details never contain a password.
    USER_CREATED = "USER_CREATED"
    USER_ROLES_CHANGED = "USER_ROLES_CHANGED"
    USER_BLOCKED = "USER_BLOCKED"
    USER_UNBLOCKED = "USER_UNBLOCKED"
    USER_PASSWORD_RESET = "USER_PASSWORD_RESET"  # noqa: S105 - event name, not a secret
    USER_PASSWORD_CHANGE_REQUIRED = "USER_PASSWORD_CHANGE_REQUIRED"  # noqa: S105
    USER_SESSIONS_REVOKED = "USER_SESSIONS_REVOKED"
    USERS_SYNCED = "USERS_SYNCED"
    # Visual atlas (Stage 9). Details carry ids, names of labels and domains, never photo content.
    DOMAIN_CREATED = "DOMAIN_CREATED"
    DOMAIN_CHANGED = "DOMAIN_CHANGED"
    LABEL_PROPOSED = "LABEL_PROPOSED"
    LABEL_APPROVED = "LABEL_APPROVED"
    LABEL_REJECTED = "LABEL_REJECTED"
    LABEL_CHANGED = "LABEL_CHANGED"
    LABEL_MERGED = "LABEL_MERGED"
    LABEL_DEPRECATED = "LABEL_DEPRECATED"
