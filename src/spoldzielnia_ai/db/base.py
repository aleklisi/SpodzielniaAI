"""Declarative base, constraint naming convention and shared columns."""

from __future__ import annotations

from datetime import datetime
from typing import Any
from uuid import UUID  # noqa: TC003 - SQLAlchemy resolves mixin annotations at runtime

from sqlalchemy import DateTime, LargeBinary, MetaData, func
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

from spoldzielnia_ai.core.ids import uuid7
from spoldzielnia_ai.db.enums import (
    AnnotationSource,
    ArticleStatus,
    ConsentStatus,
    DerivativeKind,
    DerivativeStatus,
    LlmCapability,
    LlmProviderKind,
    LlmRevisionStatus,
    LlmRoutePurpose,
    OutboxStatus,
    PromotionStatus,
    ReviewDecision,
    Role,
    ScanStatus,
    VectorOpKind,
    VisualDomainStatus,
    VisualLabelStatus,
    pg_enum,
)

# Deterministic constraint names, so Alembic can address (and drop) them in later migrations.
NAMING_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)
    type_annotation_map = {  # noqa: RUF012 - SQLAlchemy reads this class attribute
        datetime: DateTime(timezone=True),
        bytes: LargeBinary(),
        dict[str, Any]: JSONB(),
        Role: pg_enum(Role),
        ConsentStatus: pg_enum(ConsentStatus),
        ArticleStatus: pg_enum(ArticleStatus),
        ReviewDecision: pg_enum(ReviewDecision),
        ScanStatus: pg_enum(ScanStatus),
        DerivativeKind: pg_enum(DerivativeKind),
        DerivativeStatus: pg_enum(DerivativeStatus),
        PromotionStatus: pg_enum(PromotionStatus),
        VectorOpKind: pg_enum(VectorOpKind),
        OutboxStatus: pg_enum(OutboxStatus),
        LlmProviderKind: pg_enum(LlmProviderKind),
        LlmCapability: pg_enum(LlmCapability),
        LlmRevisionStatus: pg_enum(LlmRevisionStatus),
        LlmRoutePurpose: pg_enum(LlmRoutePurpose),
        VisualDomainStatus: pg_enum(VisualDomainStatus),
        VisualLabelStatus: pg_enum(VisualLabelStatus),
        AnnotationSource: pg_enum(AnnotationSource),
    }


class UUIDPrimaryKey:
    """``id`` as a time-ordered UUIDv7, generated by the application."""

    id: Mapped[UUID] = mapped_column(primary_key=True, default=uuid7)


class Timestamps:
    """``created_at`` / ``updated_at`` set by the database clock."""

    created_at: Mapped[datetime] = mapped_column(server_default=func.now())
    updated_at: Mapped[datetime] = mapped_column(server_default=func.now(), onupdate=func.now())


class Entity(UUIDPrimaryKey, Timestamps, Base):
    """Base for domain tables: UUIDv7 key plus timestamps."""

    __abstract__ = True
